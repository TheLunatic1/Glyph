use iced::widget::svg;
use iced::{Color, Length};
use std::collections::HashMap;
use std::sync::{Mutex, OnceLock};

static ICON_CACHE: OnceLock<Mutex<HashMap<(usize, u32), svg::Handle>>> = OnceLock::new();

fn color_key(c: Color) -> (u32, String, f32) {
    let r = (c.r.clamp(0.0, 1.0) * 255.0).round() as u8;
    let g = (c.g.clamp(0.0, 1.0) * 255.0).round() as u8;
    let b = (c.b.clamp(0.0, 1.0) * 255.0).round() as u8;
    let a = (c.a.clamp(0.0, 1.0) * 255.0).round() as u8;
    let packed = ((r as u32) << 24) | ((g as u32) << 16) | ((b as u32) << 8) | (a as u32);
    let hex = format!("#{r:02x}{g:02x}{b:02x}");
    (packed, hex, c.a.clamp(0.0, 1.0))
}

/// Renders an SVG icon with concrete hex stroke/fill baked directly into the SVG bytes
/// and `svg::Style { color: None }`, completely avoiding `iced_wgpu`'s un-premultiplied tint bug
/// that produces hazy anti-aliased halos around vector edges.
fn icon_svg<'a>(raw: &'static str, size: f32, color: Color) -> svg::Svg<'a> {
    let (packed, hex, alpha) = color_key(color);
    let ptr_key = raw.as_ptr() as usize;

    let cache = ICON_CACHE.get_or_init(|| Mutex::new(HashMap::new()));
    let handle = {
        let mut guard = cache.lock().expect("icon cache mutex poisoned");
        guard
            .entry((ptr_key, packed))
            .or_insert_with(|| {
                let mut baked = raw.replace("currentColor", &hex);
                let size_attrs = if alpha < 0.999 {
                    format!(r#"<svg width="24" height="24" opacity="{alpha:.3}""#)
                } else {
                    r#"<svg width="24" height="24""#.to_string()
                };
                baked = baked.replacen("<svg", &size_attrs, 1);
                svg::Handle::from_memory(baked.into_bytes())
            })
            .clone()
    };

    let snapped = size.round().max(1.0);
    svg(handle)
        .width(Length::Fixed(snapped))
        .height(Length::Fixed(snapped))
        .style(|_, _| svg::Style { color: None })
}

